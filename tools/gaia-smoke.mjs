import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const base=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const html=fs.readFileSync(path.join(base,'index.html'),'utf8');
const scripts=[...html.matchAll(/<script src="([^"]+)"/g)].map(x=>x[1]);
for (const file of scripts) assert(fs.existsSync(path.join(base,file)),`Missing script: ${file}`);
assert(!html.includes('https://') && !html.includes('http://'),'Offline entry must not call a remote URL');
for (let i=1;i<=8;i++) assert(fs.existsSync(path.join(base,`assets/backgrounds/stage${i}.png`)),`Background ${i} absent`);
for (const file of ['balls-paddles.png','glass-bricks.png']) assert(fs.existsSync(path.join(base,'assets/sprites',file)));
for (const file of ['hero-idle.png','hero-hit.png','hero-win.png','hero-shy.png']) assert(fs.existsSync(path.join(base,'assets/characters',file)));

const listeners = {};
const noop=()=>{};
const gradients={addColorStop:noop};
const fakeCtx=new Proxy({}, {get(o,k){if(k==='createLinearGradient'||k==='createRadialGradient')return()=>gradients;if(k==='measureText')return text=>({width:String(text).length*10});return o[k]??noop;},set(o,k,v){o[k]=v;return true;}});
const canvas={width:800,height:800,style:{},getContext:()=>fakeCtx,addEventListener:(name,fn)=>listeners[name]=fn,getBoundingClientRect:()=>({left:0,top:0,width:800,height:800})};
const window={addEventListener:noop,GaiaSound:{brick:noop,lose:noop,paddle:noop,powerUp:noop}};
const context=vm.createContext({window,console,performance:{now:()=>1000},requestAnimationFrame:()=>1,cancelAnimationFrame:noop,Math});
for(const script of ['js/config-inline.js','js/engine.js','js/renderer.js']) vm.runInContext(fs.readFileSync(path.join(base,script),'utf8'),context);
const Engine=vm.runInContext('GameEngine',context),Renderer=vm.runInContext('Renderer',context);
const engine=new Engine(canvas);
await engine.loadConfigs();
assert.equal(engine.levelsConfig.levels.length,8,'Expected eight established stages');
engine.selectedShip={...engine.shipsConfig.ships[1],width:138,height:25};
window.GaiaArt={backgrounds:[],balls:{draw:()=>false},bricks:{draw:()=>false}};
const renderer=new Renderer(engine);
for(let i=0;i<8;i++){
  engine.loadLevel(i);
  assert(engine.bricks.length>8,`Level ${i+1} is empty`);
  assert(engine.bricks.every(b=>b.x>=0&&b.x+b.width<=800),'A block is outside square board');
  assert(engine.bricks.some(b=>b.width>=30),'Invalid shape');
  engine.state='playing';
  renderer.render();
}
engine.loadLevel(0);
engine.state='playing';
engine.launchBall();
assert(!engine.ballAttached);
engine.update(16.67);
engine.activatePower(engine.powersConfig.powers.find(p=>p.effect==='expand'));
assert(engine.paddle.width>engine.paddle.baseWidth);
engine.updatePowerTimers(12000);
assert.equal(engine.paddle.width,engine.paddle.baseWidth,'Expand must expire by game time');
engine.activatePower(engine.powersConfig.powers.find(p=>p.effect==='laser'));
assert(engine.laserActive);
engine.updatePowerTimers(9000);
assert(!engine.laserActive,'Laser must expire');
engine.activatePower(engine.powersConfig.powers.find(p=>p.effect==='multiball'));
assert.equal(engine.balls.length,3);
const brick=engine.bricks.find(b=>!b.indestructible);
assert(brick);
const before=engine.score;
engine.balls=[{x:brick.x+brick.width/2,y:brick.y+brick.height/2,radius:8,dx:0,dy:-3,speed:4,trail:[]}];
engine.checkBrickCollisions(engine.balls[0]);
assert(engine.score>before,'Block collision must award points');
engine.state='paused';
const stationary=engine.balls[0].x;
engine.update(1000);
assert.equal(engine.balls[0].x,stationary,'Game must freeze when paused');
console.log(JSON.stringify({result:'PASS',stages:8,blocks:'collision/tintable art',powers:'multiball/laser/expansion',squareBoard:true,offlineAssets:true,pause:true},null,2));
